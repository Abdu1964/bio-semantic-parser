#!/usr/bin/env python3
"""Account for every Biolink predicate in the taxonomy, from the local Biolink model.

Writes src/schema/biolink_generated.py (coverage status of each predicate, the canonical biological predicates
the taxonomy adds, inverse → canonical map) and the generated enum block in src/schema/taxonomy.py.
Names, definitions, domains and ranges are Biolink's; nothing else is added.

    python tools/build_biolink_coverage.py [path/to/biolink-model.yaml]
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
DEFAULT = ["tools/.schema_cache/biolink_model_v4.4.2.yaml", "src/schema/data/biolink-model.yaml"]
BEGIN, END = "    # >>> generated by tools/build_biolink_coverage.py", "    # <<< generated"
# Predicates about publications, studies or schema terms, not biological findings
NOT_FINDINGS = {"provider": "bibliographic", "has completed": "study status", "completed by": "study status",
                "has not completed": "study status", "not completed by": "study status",
                "has molecular consequence": "range is an ontology class",
                "is molecular consequence of": "domain is an ontology class"}


# Entity types whose name is not a Biolink class name → the Biolink class they align to (all exist in Biolink 4.4.2)
ENTITY_CLASS_ALIGN = {
    "NON_CODING_RNA": "noncoding RNA product", "GENOMIC_VARIANT": "sequence variant", "STRUCTURAL_VARIANT": "sequence variant",
    "ENHANCER": "regulatory region", "SUPER_ENHANCER": "regulatory region", "PROMOTER": "regulatory region",
    "EPIGENOMIC_FEATURE": "genomic entity", "MOTIF": "nucleic acid sequence motif", "TAD": "genomic entity",
    "THREE_D_GENOME_STRUCTURE": "genomic entity", "CHROMOSOME": "genomic entity", "MOLECULAR_INTERACTION": "molecular activity",
    "REACTION": "molecular activity", "MOLECULAR_FUNCTION": "molecular activity", "CANCER": "disease",
    "PHENOTYPE": "phenotypic feature", "SYMPTOM": "clinical finding", "ANATOMY": "anatomical entity",
    "TISSUE": "anatomical entity", "CELL_TYPE": "cell", "DEVELOPMENTAL_STAGE": "life stage", "ORGANISM": "organism taxon",
    "POPULATION": "population of individual organisms", "DISEASE_OUTCOME": "disease or phenotypic feature outcome",
    "MICRO_RNA": "microRNA", "SI_RNA": "siRNA", "EXPERIMENTAL_FACTOR": "named thing", "SEQUENCE_TYPE": "named thing",
    "OTHER": "named thing",
}
# NER tagger labels that are not entity type names → Biolink class (unknown labels leave the prompt unfiltered)
NER_LABEL_ALIGN = {
    "GENE_OR_GENE_PRODUCT": "gene", "GGP": "gene", "DNA": "genomic entity", "SO": "genomic entity", "RNA": "RNA product",
    "SIMPLE_CHEMICAL": "chemical entity", "CHEMICAL": "chemical entity", "CHEBI": "chemical entity", "AMINO_ACID": "chemical entity",
    "CELL": "cell", "CL": "cell", "TAXON": "organism taxon", "SPECIES": "organism taxon",
    "MULTI_TISSUE_STRUCTURE": "anatomical entity", "ORGAN": "anatomical entity", "ORGANISM_SUBDIVISION": "anatomical entity",
    "ANATOMICAL_SYSTEM": "anatomical entity", "IMMATERIAL_ANATOMICAL_ENTITY": "anatomical entity",
    "DEVELOPING_ANATOMICAL_STRUCTURE": "anatomical entity", "ORGANISM_SUBSTANCE": "anatomical entity",
    "PATHOLOGICAL_FORMATION": "disease or phenotypic feature",
}


def _snake(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def _canonical(slot: dict) -> bool:
    v = (slot.get("annotations") or {}).get("canonical_predicate")
    v = v.get("value") if isinstance(v, dict) else v
    return str(v).lower() == "true"


def main(path: str) -> None:
    m = yaml.safe_load(Path(path).read_text())
    slots, classes = m["slots"], m.get("classes", {})

    def is_pred(n, seen=()):
        if n == "related to":
            return True
        p = (slots.get(n) or {}).get("is_a")
        return bool(p) and p not in seen and is_pred(p, seen + (n,))

    def ancestors(c, seen=()):
        if not c or c in seen:
            return set()
        k = classes.get(c) or {}
        out = {c}
        for p in [k.get("is_a"), *(k.get("mixins") or [])]:
            out |= ancestors(p, seen + (c,))
        return out

    preds = sorted(n for n in slots if is_pred(n))
    from src.schema import taxonomy as T
    import src.schema.biolink_generated as G
    generated_values = {g["value"] for g in G.GENERATED}
    ours = {v.split(":", 1)[1].split(" ")[0] for r, v in T.BIOLINK_MAPPING.items() if r.value not in generated_values}

    inverse = {}
    for n in preds:
        i = (slots[n] or {}).get("inverse")
        if i in slots:
            inverse[n] = i
            inverse.setdefault(i, n)

    status, add = {}, []
    for n in preds:
        s, sn = slots[n] or {}, _snake(n)
        inv = inverse.get(n)
        if sn in ours:
            status[n] = "direct"
        elif s.get("deprecated"):
            status[n] = "not applicable: deprecated"
        elif s.get("abstract") or s.get("mixin"):
            status[n] = "not applicable: abstract or mixin"
        elif n in NOT_FINDINGS:
            status[n] = f"not applicable: {NOT_FINDINGS[n]}"
        elif "match" in n or n in ("same as", "related to", "related to at concept level", "related to at instance level",
                                   "opposite of", "mentions", "mentioned by", "occurs together in literature with"):
            status[n] = "not applicable: mapping or literature co-occurrence"
        elif {"publication", "information content entity", "agent"} & (ancestors(s.get("domain")) | ancestors(s.get("range"))):
            status[n] = "not applicable: bibliographic"
        elif inv and _snake(inv) in ours:
            status[n] = f"inverse of {_snake(inv)}"
        elif inv and inv in slots and not _canonical(s) and (_canonical(slots[inv]) or s.get("inverse") == inv):
            # Biolink: the canonical direction is stored; without a canonical mark, the slot declaring `inverse` is the inverse
            status[n] = f"inverse of {_snake(inv)}"
        else:
            status[n] = "added"
            add.append({"value": sn, "biolink": n, "enum": sn.upper(),
                        "definition": " ".join((s.get("description") or "").split()),
                        "domain": s.get("domain") or "", "range": s.get("range") or "", "is_a": s.get("is_a") or ""})

    inverse_map = {_snake(n): v.split("inverse of ", 1)[1] for n, v in status.items() if v.startswith("inverse of ")}

    def slot_value(n, key, seen=()):                          # domain/range, inherited along is_a as in Biolink
        sl = slots.get(n) or {}
        if sl.get(key) or not sl.get("is_a") or n in seen:
            return sl.get(key) or ""
        return slot_value(sl["is_a"], key, seen + (n,))

    entity_class = {}
    for e in T.EntityType:
        c = e.value.lower().replace("_", " ")
        c = c if c in classes else ENTITY_CLASS_ALIGN.get(e.value, "")
        assert c in classes, f"{e.value}: '{c}' is not a Biolink class"
        entity_class[e.value] = c
    ner_class = {k: v for k, v in NER_LABEL_ALIGN.items()}
    assert all(v in classes for v in ner_class.values())
    rel_names = {r.value: v.split(":", 1)[1].split(" ")[0].replace("_", " ") for r, v in T.BIOLINK_MAPPING.items()}
    rel_names.update({a["value"]: a["biolink"] for a in add})
    domain_range = {r: (slot_value(b, "domain"), slot_value(b, "range")) for r, b in sorted(rel_names.items()) if b in slots}
    used = set(entity_class.values()) | set(ner_class.values())
    ancestors_of = {c: sorted(ancestors(c)) for c in sorted(used)}
    lines = ['"""Generated by tools/build_biolink_coverage.py from the local Biolink model — do not edit by hand."""',
             f"BIOLINK_VERSION = {m.get('version')!r}", "", "# Every Biolink predicate and how the taxonomy covers it",
             "COVERAGE = {"] + [f"    {n!r}: {v!r}," for n, v in status.items()] + ["}", "",
             "# Canonical biological predicates added to the taxonomy (Biolink name, definition, domain, range)",
             "GENERATED = ["] + [f"    {a!r}," for a in add] + ["]", "",
             "# Entity type → Biolink class", "ENTITY_CLASS = {"] + [f"    {k!r}: {v!r}," for k, v in entity_class.items()] + ["}", "",
             "# NER tagger label → Biolink class (labels that are entity type names use ENTITY_CLASS)",
             "NER_LABEL_CLASS = {"] + [f"    {k!r}: {v!r}," for k, v in ner_class.items()] + ["}", "",
             "# Relation → (Biolink domain, Biolink range); empty = any",
             "DOMAIN_RANGE = {"] + [f"    {k!r}: {v!r}," for k, v in domain_range.items()] + ["}", "",
             "# Biolink class → its ancestors and mixins (for domain/range checks without the Biolink file)",
             "ANCESTORS = {"] + [f"    {k!r}: {v!r}," for k, v in ancestors_of.items()] + ["}", "",
             "# Inverse predicate → canonical relation (stored with subject and object swapped)",
             "INVERSE_TO_CANONICAL = {"] + [f"    {k!r}: {v!r}," for k, v in sorted(inverse_map.items())] + ["}", ""]
    (ROOT / "src/schema/biolink_generated.py").write_text("\n".join(lines), encoding="utf-8")

    tax = (ROOT / "src/schema/taxonomy.py").read_text(encoding="utf-8")
    block = BEGIN + f" (Biolink {m.get('version')}) — canonical predicates added from the local Biolink model\n" + "".join(
        f'    {a["enum"]:<40} = "{a["value"]}"\n' for a in add if a["enum"] not in T.RelationType.__members__
        or a["value"] in generated_values) + END + "\n"
    if BEGIN in tax:
        tax = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _: block, tax, flags=re.S)
    else:
        anchor = "\n\n# ══════════"
        i = tax.index("class RelationType(str, Enum):")
        j = tax.index(anchor, i)
        tax = tax[:j] + "\n\n" + block.rstrip("\n") + tax[j:]
    (ROOT / "src/schema/taxonomy.py").write_text(tax, encoding="utf-8")

    from collections import Counter
    print(f"Biolink {m.get('version')}: {len(preds)} predicates —",
          dict(Counter(v.split(":")[0] if v.startswith("not") else v.split(" of ")[0] for v in status.values())))
    print(f"added {len(add)}; inverses mapped {len(inverse_map)}")


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else next((p for p in DEFAULT if (ROOT / p).exists()), None)
    if not arg:
        sys.exit("No local Biolink model file found; pass its path.")
    main(str(ROOT / arg) if not Path(arg).is_absolute() else arg)
